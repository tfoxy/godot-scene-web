// MIR-1 (src/loader.ts): wraps wasm-bindgen's `--target web` glue in a factory module, so that every
// client gets a fresh closure (its own `wasm` binding and instance) from ONE module record, and the
// instance is collectable once the client drops it. A page's module map keeps every module record
// it loads, so importing the plain glue per client (`?client=<n>`) keeps every instance alive.
//
//   node glue-factory.mjs <rs_gsw_wasm.js> <rs_gsw_wasm_client.js>
//
// The glue must have the shape wasm-bindgen 0.2.129 emits: no imports, top-level `export class` /
// `export function` declarations, and one closing `export { initSync, __wbg_init as default };`.
// Anything else is refused rather than guessed at.

import { readFileSync, writeFileSync } from "node:fs";

const TAIL = "export { initSync, __wbg_init as default };";

/** The factory module's source for one glue's source (throws on an unexpected shape). */
export function glueFactory(glue) {
  if (/^\s*import\b/m.test(glue))
    throw new Error(
      "glue-factory: the glue imports modules (snippets); not supported",
    );
  const tails = glue.split(TAIL).length - 1;
  if (tails !== 1)
    throw new Error(
      `glue-factory: expected one ${JSON.stringify(TAIL)}, found ${tails}`,
    );
  const names = [];
  let body = glue.replace(TAIL, "");
  body = body.replace(
    /^export (class|function|async function) ([A-Za-z_$][\w$]*)/gm,
    (_, kind, name) => {
      names.push(name);
      return `${kind} ${name}`;
    },
  );
  const left = body.match(/^\s*export\b.*$/m);
  if (left)
    throw new Error(`glue-factory: unexpected export: ${left[0].trim()}`);
  if (!names.includes("GswRs") || !names.includes("LiveCoding"))
    throw new Error("glue-factory: the glue exports no GswRs or LiveCoding");
  return [
    "// Generated by packages/render-stream-client/scripts/glue-factory.mjs from wasm-bindgen's glue:",
    "// each createGlue() call is a fresh glue (its own instance). Do not bundle; serve by URL.",
    "export const RENDER_STREAM_CLIENT_GLUE = 1;",
    "export default function createGlue() {",
    body.trimEnd(),
    `return { ${names.join(", ")}, initSync, default: __wbg_init };`,
    "}",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) {
    console.error(
      "usage: node glue-factory.mjs <rs_gsw_wasm.js> <rs_gsw_wasm_client.js>",
    );
    process.exit(2);
  }
  writeFileSync(output, glueFactory(readFileSync(input, "utf8")));
}
