/**
 * `MouseButtonMask` (core/input/input_enums.h:142-149): `1 << (button - 1)`. Godot names no mask for
 * the wheel buttons, but its web platform sets their bits while a wheel press is in flight
 * (display_server_web.cpp:706-711), so a `button_mask` may carry bits 3..6 too.
 */
export const MouseButtonMask = {
  NONE: 0,
  LEFT: 1,
  RIGHT: 2,
  MIDDLE: 4,
  XBUTTON1: 128,
  XBUTTON2: 256,
} as const;

/** `mouse_button_to_mask` (core/input/input_enums.h:151-155). Returns 0 for `MouseButton.NONE`. */
export function mouseButtonToMask(button: number): number {
  return button >= 1 ? 1 << (button - 1) : 0;
}
